// Trusted starting point baked into each release. Everything verifyBlock
// proves is relative to it: a Stacks block whose state holds one cycle's
// signer set, and a Bitcoin header to sync proof-of-work from.
//
// Bump it once per release so the signer-set walk stays short:
// 1. Pick a recent reward cycle C and a canonical Stacks block X whose burn
//    block is in C-1's prepare phase or later (its state holds set C).
// 2. Fetch X's raw block (`/v3/blocks/<id>`, keep the header bytes) and
//    `cycle-signer-set[C]` with its proof at X (`/v2/clarity/marf/<path>?tip=X&proof=1`,
//    key `mapEntryKey(SIGNERS_CONTRACT, "cycle-signer-set", uintCV(C))`).
// 3. Bitcoin: the retarget-period start (a multiple of 2016) at or below C's
//    first burn block, 666050 + 2100 * C. Blocks above X whose burn height
//    is below the Bitcoin checkpoint cannot be verified; blocks below X are
//    verified by hash chain from X instead.
// 4. Add X's header, its proof ancestors and the set proof to test/fixtures:
//    the checkpoint test re-proves the baked set against X.
import type { Checkpoint } from "./bitcoin/chain.ts";

export interface VerifyCheckpoint {
	stacks: {
		/** Raw Nakamoto header (hex) of a trusted block whose state holds `signerSet`. */
		header: string;
		/** Reward cycle `signerSet` belongs to. */
		cycle: number;
		/** `.signers` `cycle-signer-set[cycle]` as stored: hex of `(some (list ...))`. */
		signerSet: string;
	};
	/** Retarget-boundary Bitcoin header at or below the first burn block of `stacks.cycle`. */
	bitcoin: Checkpoint;
}

