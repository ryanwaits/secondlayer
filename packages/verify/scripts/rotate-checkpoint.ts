// Move MAINNET_CHECKPOINT forward one reward cycle, proven from the current one.
//
//   bun run --filter @secondlayer/verify rotate-checkpoint [--cycle C] [--api URL]
//
// The new checkpoint is accepted only if `verifyBlock`, starting from the
// checkpoint that ships today, proves its block, and the new signer set is
// MARF-proven in that block's state. Rotation therefore adds no trust: anyone
// holding the old release reaches the same new checkpoint.
//
// Writes src/checkpoint-mainnet.ts and test/fixtures/checkpoint/stacks.json
// (the header, set proof and ancestor headers test/checkpoint.test.ts re-proves
// offline). Nothing is written unless every check passes.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { uintCV } from "@secondlayer/stacks/clarity";
import { HeaderChain } from "../src/bitcoin/chain.ts";
import { cycleStart, rewardCycle } from "../src/burn.ts";
import { type Bytes, hex } from "../src/bytes.ts";
import { MAINNET_CHECKPOINT } from "../src/checkpoint.ts";
import type { VerifyCheckpoint } from "../src/checkpoint.ts";
import { blockId, parseNakamotoHeader } from "../src/header.ts";
import { mapEntryKey } from "../src/keys.ts";
import {
	marfPath,
	marfProofAncestors,
	marfValue,
	verifyMarfProof,
} from "../src/marf.ts";
import { SIGNERS_CONTRACT, decodeSignerSet } from "../src/signers.ts";
import {
	DEFAULT_API_URL,
	type ProofSource,
	SecondlayerProofSource,
} from "../src/source.ts";
import { type BlockVerification, verifyBlock } from "../src/verify-block.ts";

const ROOT = join(import.meta.dir, "..");
const RETARGET_INTERVAL = 2016;
const HEX_WIDTH = 96;

/** `.signers` `cycle-signer-set[cycle]` MARF key. */
const setKey = (cycle: number) =>
	mapEntryKey(SIGNERS_CONTRACT, "cycle-signer-set", uintCV(cycle));

const fmt = (n: number | bigint) => n.toLocaleString("en-US");

export interface CheckpointFixture {
	blockId: string;
	/** Raw Nakamoto header (hex), the checkpoint's `stacks.header`. */
	header: string;
	cycle: number;
	key: string;
	path: string;
	/** Set value as stored, hex. */
	data: string;
	/** Consensus-serialized MARF proof of `data` at `path` in the block's state. */
	proof: string;
	/** Headers (hex) of the ancestor tries the proof crosses, by block id. */
	ancestors: Record<string, string>;
}

const wrap = (s: string) =>
	[...(s.match(new RegExp(`.{1,${HEX_WIDTH}}`, "g")) ?? [])]
		.map((l) => `\t\t\t"${l}",`)
		.join("\n");

/** The text of src/checkpoint-mainnet.ts for `cp`. */
export function renderCheckpoint(
	cp: VerifyCheckpoint,
	about: { blockId: string; signers: number; weight: bigint },
): string {
	const header = parseNakamotoHeader(
		Uint8Array.from(Buffer.from(cp.stacks.header, "hex")),
	);
	const height = fmt(header.chainLength);
	const btc = fmt(cp.bitcoin.height);
	const start = cycleStart(cp.stacks.cycle);
	const where =
		cp.bitcoin.height > start
			? `inside cycle ${cp.stacks.cycle}`
			: `at or below cycle ${cp.stacks.cycle}'s first burn block ${fmt(start)}`;
	const btcHeader =
		typeof cp.bitcoin.header === "string"
			? cp.bitcoin.header
			: hex(cp.bitcoin.header);
	return `// Generated by scripts/rotate-checkpoint.ts. Do not edit by hand.
// Stacks block ${height}, cycle ${cp.stacks.cycle}, Bitcoin height ${btc}.
import type { VerifyCheckpoint } from "./checkpoint.ts";

/**
 * Mainnet: Stacks block ${height} (\`${about.blockId.slice(0, 8)}…${about.blockId.slice(-4)}\`) holding the cycle ${cp.stacks.cycle}
 * signer set (${about.signers} signers, weight ${about.weight}), and Bitcoin block ${btc} (a
 * retarget-period start ${where}). Later blocks verify forward
 * (burn height ${btc} or later); earlier ones by hash chain from ${height}.
 */
export const MAINNET_CHECKPOINT: VerifyCheckpoint = {
	stacks: {
		header: [
${wrap(cp.stacks.header)}
		].join(""),
		cycle: ${cp.stacks.cycle},
		signerSet: [
${wrap(cp.stacks.signerSet)}
		].join(""),
	},
	bitcoin: {
		height: ${cp.bitcoin.height},
		header:
			"${btcHeader}",
	},
};
`;
}

async function tipHeight(api: string): Promise<number> {
	const res = await fetch(`${api}/public/status`);
	if (!res.ok) throw new Error(`${api}/public/status: HTTP ${res.status}`);
	const j = (await res.json()) as { chainTip?: unknown };
	if (typeof j.chainTip !== "number")
		throw new Error("status answer has no chainTip");
	return j.chainTip;
}

/** The reward cycle a block's burn block falls in. A hint (unverified) for the default `--cycle`. */
async function hintedCycle(source: ProofSource, height: number) {
	const header = parseNakamotoHeader(await source.getBlock(height));
	const burn = await source.getBurnPreimage(hex(header.consensusHash));
	return rewardCycle(burn.burnHeight);
}

async function main() {
	const { values } = parseArgs({
		options: { cycle: { type: "string" }, api: { type: "string" } },
	});
	const api = values.api ?? DEFAULT_API_URL;
	const source = new SecondlayerProofSource({ baseUrl: api });
	const OLD = MAINNET_CHECKPOINT;

	const tip = (await tipHeight(api)) - 5;
	const C = values.cycle
		? Number(values.cycle)
		: (await hintedCycle(source, tip)) - 1;
	if (!Number.isInteger(C) || C < 0) throw new Error(`bad cycle ${C}`);
	if (C <= OLD.stacks.cycle) {
		console.log(`already at cycle ${OLD.stacks.cycle} (asked for ${C})`);
		return;
	}
	const start = cycleStart(C);

	// 1. Lowest Stacks height whose block verifies from OLD with a burn height in cycle C.
	let probes = 0;
	const results = new Map<number, BlockVerification>();
	const probe = async (h: number): Promise<boolean> => {
		const t0 = performance.now();
		const r = await verifyBlock(h, { source, checkpoint: OLD });
		probes++;
		// Blocks burned before the Bitcoin checkpoint cannot be verified (the
		// checkpoint only syncs forward), and they are before cycle C by definition.
		const early = r.failures[0]?.code === "before-checkpoint";
		if (!r.ok && early) {
			console.log(
				`probe ${probes}: height ${fmt(h)} burns before Bitcoin checkpoint ${fmt(OLD.bitcoin.height)}, so before cycle ${C}`,
			);
			return false;
		}
		if (!r.ok)
			throw new Error(
				`verifyBlock(${h}) from the current checkpoint failed: ${JSON.stringify(r.failures[0])}`,
			);
		results.set(h, r);
		const hit = (r.burnHeight as number) >= start;
		console.log(
			`probe ${probes}: height ${fmt(h)} burn ${fmt(r.burnHeight as number)} cycle ${r.cycle} ${hit ? "in" : "before"} cycle ${C} (${((performance.now() - t0) / 1000).toFixed(1)}s)`,
		);
		return hit;
	};
	let lo = Number(
		parseNakamotoHeader(Uint8Array.from(Buffer.from(OLD.stacks.header, "hex")))
			.chainLength,
	);
	let hi = tip;
	if (!(await probe(hi)))
		throw new Error(
			`tip ${hi} is not in cycle ${C} yet; pick an earlier --cycle`,
		);
	while (hi - lo > 1) {
		const mid = lo + Math.floor((hi - lo) / 2);
		if (await probe(mid)) hi = mid;
		else lo = mid;
	}
	const X = hi;
	const r = results.get(X) as BlockVerification;
	if (r.cycle !== C)
		throw new Error(`block ${X} is in cycle ${r.cycle}, expected ${C}`);
	const idX = r.blockId as string;
	const burnX = r.burnHeight as number;

	// 2. The new signer set, MARF-proven in X's state with the verifier's own calls.
	const raw = await source.getBlock(idX);
	const headerX = parseNakamotoHeader(raw);
	if (hex(blockId(headerX)) !== idX)
		throw new Error(`block bytes for ${idX} hash to a different id`);
	const headerBytes = raw.subarray(0, headerX.byteLength);
	const key = setKey(C);
	const path = marfPath(key);
	const answer = await source.getMarfProof(hex(path), idX);
	if (!answer) throw new Error(`no proof of signer set ${C} at ${idX}`);
	const data = answer.data.replace(/^0x/, "");
	const ancestors: Record<string, Bytes> = {};
	for (const id of marfProofAncestors(answer.proof)) {
		const ancestor = await source.getBlock(id);
		const h = parseNakamotoHeader(ancestor);
		if (hex(blockId(h)) !== id)
			throw new Error(`ancestor ${id} bytes hash to a different id`);
		ancestors[id] = ancestor.subarray(0, h.byteLength);
	}
	const headers = [
		headerX,
		...Object.values(ancestors).map((b) => parseNakamotoHeader(b)),
	];
	if (
		!verifyMarfProof({
			proof: answer.proof,
			path,
			value: marfValue(data),
			root: headerX.stateIndexRoot,
			headers,
		})
	)
		throw new Error(`signer set ${C} is not proven in block ${idX}'s state`);
	const set = decodeSignerSet(data);
	if (set.size === 0) throw new Error(`signer set ${C} is empty`);
	const weight = [...set.values()].reduce((a, b) => a + b, 0n);

	// 3. Bitcoin: the retarget-period start at or below the cycle's first burn
	// block, never behind the current checkpoint. PoW and retargets validated.
	const B = Math.max(
		Math.floor(start / RETARGET_INTERVAL) * RETARGET_INTERVAL,
		OLD.bitcoin.height,
	);
	if (B > burnX)
		throw new Error(
			`Bitcoin checkpoint ${B} is above block ${X}'s burn height ${burnX}`,
		);
	let bitcoin = OLD.bitcoin;
	if (B > OLD.bitcoin.height) {
		const chain = HeaderChain.fromCheckpoint(OLD.bitcoin);
		for (let from = OLD.bitcoin.height + 1; from <= B; ) {
			const count = Math.min(RETARGET_INTERVAL, B - from + 1);
			chain.append(await source.getBitcoinHeaders(from, count));
			from += count;
		}
		const entry = chain.headerAt(B);
		if (!entry) throw new Error(`no header at ${B}`);
		bitcoin = { height: B, header: hex(entry.raw) };
	}

	const next: VerifyCheckpoint = {
		stacks: { header: hex(headerBytes), cycle: C, signerSet: data },
		bitcoin,
	};
	writeFileSync(
		join(ROOT, "src", "checkpoint-mainnet.ts"),
		renderCheckpoint(next, { blockId: idX, signers: set.size, weight }),
	);
	const fixture: CheckpointFixture = {
		blockId: idX,
		header: hex(headerBytes),
		cycle: C,
		key,
		path: hex(path),
		data,
		proof: hex(answer.proof),
		ancestors: Object.fromEntries(
			Object.entries(ancestors).map(([id, b]) => [id, hex(b)]),
		),
	};
	writeFileSync(
		join(ROOT, "test", "fixtures", "checkpoint", "stacks.json"),
		`${JSON.stringify(fixture, null, "\t")}\n`,
	);

	const oldHeader = parseNakamotoHeader(
		Uint8Array.from(Buffer.from(OLD.stacks.header, "hex")),
	);
	console.log(`
rotated checkpoint
  stacks   ${fmt(oldHeader.chainLength)} (${hex(blockId(oldHeader))}) cycle ${OLD.stacks.cycle}
        -> ${fmt(headerX.chainLength)} (${idX}) cycle ${C}
  signers  ${set.size}, total weight ${weight}
  bitcoin  ${fmt(OLD.bitcoin.height)} -> ${fmt(bitcoin.height)} (${HeaderChain.fromCheckpoint(bitcoin).tip.hash})
  probes   ${probes} full verifications
  proven from the previous checkpoint`);
}

if (import.meta.main) await main();
